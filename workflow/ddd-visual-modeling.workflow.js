export const meta = {
    name: 'ddd-visual-modeling',
    description: '从代码和文档生成交互式事件风暴流程图',
    phases: [
        { title: '分析', detail: '提取业务信息' },
        { title: '建模', detail: 'DDD 领域建模' },
        { title: '可视化', detail: '生成交互式流程图' }
    ]
};

// 获取参数
const codePath = args?.codePath || '.';
const docPath = args?.docPath;
const scope = args?.scope || '业务领域';
const outputPath = args?.outputPath || `event-storm-${scope}.html`;

log(`🚀 开始 DDD 可视化建模流程`);
log(`📂 代码路径: ${codePath}`);
log(`📄 文档路径: ${docPath || '未提供'}`);
log(`🎯 分析范围: ${scope}`);

// ============================================
// 阶段 1: 代码与文档分析
// ============================================
phase('分析');

log('正在分析代码和文档...');

const businessDesc = await agent(
    `你是一个业务分析专家。请分析以下代码和文档，提取业务信息。

代码路径: ${codePath}
文档路径: ${docPath || '无'}
分析范围: ${scope}

请执行以下任务：

1. 扫描代码结构，识别主要的类、方法、依赖关系
2. ${docPath ? '阅读需求文档，提取业务流程和规则' : '从代码中推测业务流程'}
3. 生成统一的业务描述

输出格式：
# 业务需求描述

## 业务背景
[描述业务背景和目标]

## 核心场景
[列出主要的业务场景]

## 业务术语
[提取的业务术语和定义]

## 参与者与外部系统
[识别的参与者和外部系统]

## 业务流程与规则
[详细的业务流程描述]

## 待确认问题
[需要确认的问题]
`,
    {
        label: '业务分析',
        phase: '分析'
    }
);

if (!businessDesc) {
    log('❌ 业务分析失败');
    return { success: false, error: '业务分析失败' };
}

log('✅ 业务分析完成');

// ============================================
// 阶段 2: DDD 建模
// ============================================
phase('建模');

log('正在进行 DDD 建模...');

const domainModel = await agent(
    `你是一个 DDD 建模专家。请基于以下业务描述进行 DDD 建模。

业务描述：
${businessDesc}

请按照 DDD 事件风暴方法，执行以下步骤：

1. 识别领域事件（已发生的业务事实，完成时态命名）
2. 识别领域命令（触发事件的动作，祈使句命名）
3. 识别聚合（承载业务逻辑的对象）
4. 识别 Policy（事件驱动的自动化策略）

输出格式必须严格遵循以下结构：

## 领域命令清单
| 编号 | 命令名称 | 类名 | 触发者 | 输入数据 | 前置条件 | 产生事件 |
|------|---------|------|--------|---------|---------|---------|
| C1   | 创建订单 | CreateOrderCommand | 用户 | 商品列表、收货地址 | 商品库存充足 | E1 |

## 领域事件清单
| 编号 | 事件名称 | 类名 | 业务含义 | 前置事件 |
|------|---------|------|---------|---------|
| E1   | 已创建订单 | OrderCreatedEvent | 用户成功下单 | - |

## 聚合清单
### 聚合：订单 (Order)
- 聚合根：Order
- 聚合 ID：OrderId
- 命令-事件映射：C1 → E1, C2 → E2
- 内部状态数据：商品列表、总金额、订单状态
- 不变量：订单总金额 = 所有商品金额之和

## Policy 清单
| 编号 | 策略名称 | 类名 | 监听事件 | 触发命令 | 业务规则描述 |
|------|---------|------|---------|---------|-------------|
| P1   | 支付后通知发货 | NotifyShipmentPolicy | E2 | C3 | 支付成功后自动通知 |

请确保：
- 命令和事件编号连续（C1, C2, ... 和 E1, E2, ...）
- 每个命令都有对应的产生事件
- 聚合的命令-事件映射格式为：C1 → E1, C2 → E2
`,
    {
        label: 'DDD 建模',
        phase: '建模'
    }
);

if (!domainModel) {
    log('❌ DDD 建模失败');
    return { success: false, error: 'DDD 建模失败' };
}

log('✅ DDD 建模完成');

// ============================================
// 阶段 3: 生成交互式流程图
// ============================================
phase('可视化');

log('正在生成交互式流程图...');

const htmlContent = await agent(
    `你是一个可视化专家。请基于以下 DDD 建模结果生成交互式事件风暴流程图。

建模结果：
${domainModel}

请生成一个完整的 HTML 文件，包含以下功能：

1. 使用 Mermaid 渲染事件风暴流程图
2. 流程：Command → Aggregate → Event → Policy → Command
3. 支持滚轮缩放（30% - 300%）
4. 支持整个画布拖拽
5. 支持点击节点查看详情
6. 支持高亮直接邻居节点

参考模板：${codePath}/examples/event-storm-demo.html

关键要求：
- 必须是完整的独立 HTML 文件（包含所有 CSS 和 JavaScript）
- 必须包含缩放和拖拽功能
- 节点颜色：Command=黄色、Event=红色、Aggregate=蓝色、Policy=紫色
- 详情面板必须显示完整的建模信息

**高亮逻辑（重要）**：
- 只高亮点击节点的直接邻居，不要递归追踪
- 使用 visited Set 防止死循环
- 规则：
  * 点击命令 → 高亮：自己 + 操作的聚合 + 产生的事件（不继续追踪事件的下游）
  * 点击事件 → 高亮：自己 + 产生它的命令和聚合 + 监听它的策略（不继续追踪策略触发的命令）
  * 点击策略 → 高亮：自己 + 监听的事件 + 触发的命令（不继续追踪）
  * 点击聚合 → 高亮：自己 + 操作它的所有命令 + 它产生的所有事件（不继续追踪）
- 目的：保持聚焦，避免点亮整个系统

请直接输出完整的 HTML 代码，不要有任何额外说明。
`,
    {
        label: '生成 HTML',
        phase: '可视化'
    }
);

if (!htmlContent) {
    log('❌ 流程图生成失败');
    return { success: false, error: '流程图生成失败' };
}

log('✅ 流程图生成完成');

// ============================================
// 保存文件
// ============================================
log(`正在保存文件到: ${outputPath}`);

// TODO: 这里需要调用文件写入接口
// 目前先返回 HTML 内容，让用户手动保存

return {
    success: true,
    outputPath: outputPath,
    htmlContent: htmlContent,
    summary: {
        scope: scope,
        codePath: codePath,
        docPath: docPath,
        phases: [
            '✅ 阶段 1: 业务分析完成',
            '✅ 阶段 2: DDD 建模完成',
            '✅ 阶段 3: 流程图生成完成'
        ]
    }
};
